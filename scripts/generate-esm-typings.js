'use strict';

// Generates typings/objection/index.d.mts, the types of the ES module entry,
// from the members of `namespace Objection` in typings/objection/index.d.ts.
//
// index.d.ts uses `export =`, which `export *` can't re-export, so every
// member is re-exported by name with `export import X = objection.X`. That
// re-exports the value and the type under the same name, which is what
// `import { Model, type ModelObject } from '@abedmurrar/objection'` needs.
//
//   node scripts/generate-esm-typings.js           write the file
//   node scripts/generate-esm-typings.js --check   fail if it's out of date

const fs = require('node:fs');
const path = require('node:path');

const typingsDir = path.join(__dirname, '..', 'typings', 'objection');
const sourcePath = path.join(typingsDir, 'index.d.ts');
const targetPath = path.join(typingsDir, 'index.d.mts');

// Declarations directly in the namespace, which Biome indents by 2 spaces.
const MEMBER =
  /^ {2}(?:export )?(?:declare )?(?:abstract )?(?:interface|type|class|const|let|var|function|namespace|enum) ([A-Za-z_$][\w$]*)/;

function members(source) {
  const lines = source.split('\n');
  const start = lines.findIndex((line) => line.startsWith('declare namespace Objection {'));

  if (start === -1) {
    throw new Error('`declare namespace Objection {` not found in index.d.ts');
  }

  const end = lines.findIndex((line, i) => i > start && line === '}');
  const names = new Set();

  for (const line of lines.slice(start + 1, end)) {
    const match = line.match(MEMBER);

    if (match) {
      names.add(match[1]);
    }
  }

  return [...names];
}

function generate() {
  const names = members(fs.readFileSync(sourcePath, 'utf8'));

  return [
    '// Generated by scripts/generate-esm-typings.js from index.d.ts. Do not edit.',
    '//',
    '// The types of the ES module entry (lib/index.mjs).',
    '',
    "import objection from './index.js';",
    '',
    'export default objection;',
    '',
    ...names.map((name) => `export import ${name} = objection.${name};`),
    '',
  ].join('\n');
}

function main() {
  const generated = generate();

  if (process.argv.includes('--check')) {
    const current = fs.existsSync(targetPath) ? fs.readFileSync(targetPath, 'utf8') : '';

    if (current !== generated) {
      console.error('index.d.mts is out of date. Run `node scripts/generate-esm-typings.js`.');
      process.exit(1);
    }
  } else {
    fs.writeFileSync(targetPath, generated);
  }
}

main();
